"""Builds eval/RESULTS.md from the JSON files written by coach-eval and mlx-eval."""
import json
import pathlib
import sys

here = pathlib.Path(__file__).parent
files = sys.argv[1:] or ["ollama.json", "mlx-4b.json", "mlx-1b.json"]

rows = {}
for name in files:
    for t in json.loads((here / name).read_text()):
        label = t["model"] if "on-device" in t["model"] or t["model"] == "rules" else f'{t["model"]} (Ollama)'
        rows.setdefault(label, []).append(t)


def pct(ts, key):
    return f'{round(100 * sum(1 for t in ts if t[key]) / len(ts))}%'


NO_FLAG = {"steady", "beginner"}


def cites(t):
    # Only flagged runners have a number worth citing.
    return t["persona"] in NO_FLAG or t["citesNumber"]


def model_pass(t):
    ok = t["valid"] and t["directionOK"] and t["hardOK"] and t["paceOK"]
    return ok and not any(h.startswith("floor") for h in t["guardrailHits"])


out = [
    "# Eval results",
    "",
    "Six synthetic runners, each with an expected coach behavior (see README). Generated by `eval/summarize.py`.",
    "",
    "| Coach | Runs | Valid | Final plan right | Model right on its own | Note matches plan | Note cites the flagged number | Avg time |",
    "|---|---|---|---|---|---|---|---|",
]
for label, ts in rows.items():
    final = round(100 * sum(1 for t in ts if t["valid"] and t["directionOK"] and t["hardOK"] and t["paceOK"]) / len(ts))
    own = round(100 * sum(1 for t in ts if model_pass(t)) / len(ts))
    lat = sum(t["latency"] for t in ts) / len(ts)
    out.append(
        f'| {label} | {len(ts)} | {pct(ts, "valid")} | {final}% | {own}% | {pct(ts, "messageKept")} | {round(100 * sum(1 for t in ts if cites(t)) / len(ts))}% | {lat:.1f}s |'
    )

out += ["", "Times: Apple M2 Pro. On-device rows use the same MLX weights the iPhone downloads.", "", "## Sample notes", ""]
for label, ts in rows.items():
    if label == "rules":
        continue
    out.append(f"**{label}**")
    out.append("")
    seen = set()
    for t in ts:
        if t["persona"] in seen:
            continue
        seen.add(t["persona"])
        out.append(f'- *{t["persona"]}*: {t["message"]}')
    out.append("")

(here / "RESULTS.md").write_text("\n".join(out))
print("\n".join(out[:12]))
